#!/usr/bin/env python3
"""
Generates the Nova Bank launcher icon from one geometry, so every format matches:

  res/drawable/ic_launcher_background.xml   adaptive background (navy gradient + glow)
  res/drawable/ic_launcher_foreground.xml   adaptive foreground (cyan cookie + white N)
  res/drawable/ic_launcher_monochrome.xml   themed icon (Android 13+): cookie with the N cut out
  res/mipmap-*/ic_launcher(_round).png      legacy icons for Android 7.x (API 24-25)
  ic_launcher-playstore.png                 512 px Play Store icon

The mark is the same as the Login screen and splash: a 9-sided "cookie" (Material 3
Expressive) in brand cyan, with an "N" whose points match avd_splash_mark.xml.

Run from the repo root:  python3 tools/launcher_icon.py   (needs Pillow)
"""
import math
import os
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main')
RES = os.path.join(ROOT, 'res')

NAVY_DEEP, NAVY, NAVY_LIGHT = (0x04, 0x1A, 0x2E), (0x0A, 0x2E, 0x4D), (0x12, 0x42, 0x6B)
CYAN, CYAN_LIGHT = (0x00, 0xA9, 0xCC), (0x6F, 0xD8, 0xF0)

# Adaptive icons are 108 units; launchers may crop to a 66-unit circle, so the mark stays inside it.
C = 54.0
R = 25.0            # cookie base radius; peaks reach R * (1 + AMP) = 27 — inside the 33 safe radius, with air around it
AMP = 0.08          # scallop depth
LOBES = 9
# "N" in units of a 56-radius disc (same points as the splash vector), scaled to the cookie.
N_POINTS = [(-21, 26), (-21, -26), (-9, -26), (9, 4), (9, -26), (21, -26), (21, 26), (9, 26), (-9, -4), (-9, 26)]
N_SCALE = R / 56 * 1.04


def cookie(cx=C, cy=C, r=R, steps=216):
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        rr = r * (1 + AMP * math.cos(LOBES * (t + math.pi / 2)))  # a lobe points straight up
        pts.append((cx + rr * math.cos(t), cy + rr * math.sin(t)))
    return pts


def letter(cx=C, cy=C, s=N_SCALE):
    return [(cx + x * s, cy + y * s) for x, y in N_POINTS]


def path(points):
    head, *rest = points
    return f"M{head[0]:.2f},{head[1]:.2f} " + " ".join(f"L{x:.2f},{y:.2f}" for x, y in rest) + " Z"


def hex_(rgb, a=0xFF):
    return "#%02X%02X%02X%02X" % (a, *rgb)


def write(rel, text):
    with open(os.path.join(RES, rel), 'w') as f:
        f.write(text)


def write_vectors():
    head = ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/launcher_icon.py; edit the script, not this file. -->\n')
    write('drawable/ic_launcher_background.xml', head + f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108"
                android:startColor="{hex_(NAVY_DEEP)}" android:centerColor="{hex_(NAVY)}" android:endColor="{hex_(NAVY_LIGHT)}" />
        </aapt:attr>
    </path>
    <!-- Soft cyan glow behind the mark, like the app background. -->
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="66" android:centerY="70" android:gradientRadius="52"
                android:startColor="{hex_(CYAN, 0x59)}" android:endColor="{hex_(CYAN, 0x00)}" />
        </aapt:attr>
    </path>
</vector>
''')
    write('drawable/ic_launcher_foreground.xml', head + f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- Cookie9Sided badge, lit from the top-left. -->
    <path android:pathData="{path(cookie())}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="30" android:startY="24" android:endX="80" android:endY="86"
                android:startColor="{hex_(CYAN_LIGHT)}" android:centerColor="{hex_(CYAN)}" android:endColor="#FF0088A8" />
        </aapt:attr>
    </path>
    <path android:fillColor="#FFFFFFFF" android:pathData="{path(letter())}" />
</vector>
''')
    # Themed icons: one colour, the system tints it. Even-odd punches the N out of the cookie.
    write('drawable/ic_launcher_monochrome.xml', head + f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="#FF000000" android:fillType="evenOdd"
        android:pathData="{path(cookie())} {path(letter())}" />
</vector>
''')


# ---------- Raster (legacy + Play Store) ----------

SS = 4  # supersampling for anti-aliasing


def gradient(size, colors):
    """Top-left → bottom-right gradient across a square, through 2 or 3 colours (matches the vectors)."""
    vertical = Image.linear_gradient('L').resize((size, size))
    horizontal = vertical.rotate(90)  # 90° keeps the square fully covered
    g = ImageChops.add(vertical, horizontal, scale=2)  # dark top-left → light bottom-right
    def ramp(v):
        t = v / 255
        if len(colors) == 2:
            a, b, u = colors[0], colors[1], t
        elif t < 0.5:
            a, b, u = colors[0], colors[1], t * 2
        else:
            a, b, u = colors[1], colors[2], (t - 0.5) * 2
        return tuple(round(a[i] + (b[i] - a[i]) * u) for i in range(3))
    lut = [ramp(v) for v in range(256)]
    rgb = Image.merge('RGB', [g.point([c[i] for c in lut]) for i in range(3)])
    return rgb.convert('RGBA')


def render_full(px):
    """The whole 108-unit adaptive icon, unmasked, at px × px."""
    n = px * SS
    k = n / 108
    img = gradient(n, [NAVY_DEEP, NAVY, NAVY_LIGHT])
    # Soft cyan glow: a blurred disc, same place as the vector's radial gradient.
    mask = Image.new('L', (n, n), 0)
    ImageDraw.Draw(mask).ellipse(((66 - 30) * k, (70 - 30) * k, (66 + 30) * k, (70 + 30) * k), fill=120)
    mask = mask.filter(ImageFilter.GaussianBlur(20 * k))
    layer = Image.new('RGBA', (n, n), CYAN + (0,))
    layer.putalpha(mask)
    img = Image.alpha_composite(img, layer)

    shape = Image.new('L', (n, n), 0)
    ImageDraw.Draw(shape).polygon([(x * k, y * k) for x, y in cookie()], fill=255)
    fill = gradient(n, [CYAN_LIGHT, CYAN, (0x00, 0x88, 0xA8)])
    fill.putalpha(shape)
    # A faint drop shadow lifts the badge off the background.
    shadow = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    sh = shape.filter(ImageFilter.GaussianBlur(2.2 * k)).point(lambda v: int(v * 0.35))
    shadow.putalpha(sh)
    img = Image.alpha_composite(img, shadow.transform((n, n), Image.AFFINE, (1, 0, 0, 0, 1, -1.2 * k)))
    img = Image.alpha_composite(img, fill)
    ImageDraw.Draw(img).polygon([(x * k, y * k) for x, y in letter()], fill=(255, 255, 255, 255))
    return img


def legacy(px, round_):
    """Launchers show the middle 72 of the 108 units; crop to that, then mask."""
    full = render_full(round(px * 108 / 72))
    n = full.size[0]
    inset = (n - px * SS) // 2
    img = full.crop((inset, inset, inset + px * SS, inset + px * SS))
    mask = Image.new('L', img.size, 0)
    d = ImageDraw.Draw(mask)
    if round_:
        d.ellipse((0, 0, img.size[0] - 1, img.size[1] - 1), fill=255)
    else:
        d.rounded_rectangle((0, 0, img.size[0] - 1, img.size[1] - 1), radius=img.size[0] * 0.22, fill=255)
    img.putalpha(mask)
    return img.resize((px, px), Image.LANCZOS)


def write_rasters():
    for folder, px in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
        d = os.path.join(RES, f'mipmap-{folder}')
        for name in ('ic_launcher', 'ic_launcher_round'):
            for ext in ('.webp', '.png'):  # replace whichever format was there
                p = os.path.join(d, name + ext)
                if os.path.exists(p):
                    os.remove(p)
            legacy(px, name.endswith('round')).save(os.path.join(d, name + '.png'), optimize=True)
    # Play Store: full square; Play applies its own mask.
    render_full(512).resize((512, 512), Image.LANCZOS).save(os.path.join(ROOT, 'ic_launcher-playstore.png'), optimize=True)


if __name__ == '__main__':
    write_vectors()
    write_rasters()
    print('Launcher icon generated.')
